/**
 * The words too ordinary to be worth a card.
 *
 *   node scripts/build-common.mjs [count]
 *
 * Picking the words out of a shared passage needs a floor. Without one the
 * reader is offered "about", "error" and "border" alongside "ephemeral",
 * because all four happen to appear in the glossary as cross-references under
 * something else.
 *
 * The cutoff is a frequency rank over the Google Web Trillion Word Corpus,
 * the same list the deck is chosen from. Ten thousand sits in a gap you can
 * see in the data: about is 36th, error 899th, contemporary 2,871st, border
 * 3,282nd and refuse 7,367th - none of them a card anyone wants - while prose
 * is 13,619th, endemic 23,588th and ephemeral 39,014th. Everything under the
 * line is a word somebody reading English already has.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SOURCE = join(HERE, '.cache', 'count_1w.txt')
const OUT = join(HERE, '..', 'src', 'data', 'common.ts')
const URL = 'https://norvig.com/ngrams/count_1w.txt'

const cutoff = Number(process.argv[2] ?? 10000)

if (!existsSync(SOURCE)) {
  console.error(`No frequency list at ${SOURCE}.\nRun npm run build:deck first, or download ${URL} to that path.`)
  process.exit(1)
}

const words = []
const seen = new Set()
for (const line of readFileSync(SOURCE, 'utf8').split('\n')) {
  const word = line.split('\t')[0]?.trim().toLowerCase()
  // Three letters and under are never offered as cards anyway, and leaving
  // them out buys a fifth of the file back.
  if (!word || word.length < 4 || !/^[a-z]+$/.test(word) || seen.has(word)) continue
  seen.add(word)
  words.push(word)
  if (words.length >= cutoff) break
}

const file = `/**
 * Generated by scripts/build-common.mjs - do not edit by hand.
 *
 * The ${words.length} most frequent English words of four letters or more, from the
 * Google Web Trillion Word Corpus. Used as a floor when picking the words
 * worth knowing out of a passage: anything in here is already known.
 */
const WORDS = \`${words.join(' ')}\`

export const COMMON: ReadonlySet<string> = new Set(WORDS.split(' '))
`

writeFileSync(OUT, file, 'utf8')
console.log(`${words.length} common words -> ${OUT}`)
